import test from 'node:test';
import assert from 'node:assert/strict';
const api = await import('../../ui/widget-location.mjs').catch(() => ({}));
const city = { name: 'İstanbul', label: 'İstanbul, Türkiye', countryCode: 'TR', country: 'Türkiye', city: 'İstanbul', district: '', latitude: 41.01, longitude: 28.98 };
const district = { ...city, name: 'Kadıköy', district: 'Kadıköy', latitude: 40.99, longitude: 29.03 };
const saved = { countryCode: 'TR', country: 'Türkiye', city: 'İstanbul', district: 'Kadıköy', latitude: 40.99, longitude: 29.03, cityLatitude: 41.01, cityLongitude: 28.98 };
test('only selected scoped places save, city coordinates survive optional district and reopen', () => {
  assert.equal(typeof api.createLocationDraft, 'function', 'location draft implementation required');
  let draft = api.createLocationDraft({ city: 'old city', location: null });
  assert.equal(draft.texts.city, 'old city'); assert.equal(api.locationPatch(draft, []), null);
  draft = api.choosePlace(draft, 'country', { code: 'TR', name: 'Türkiye' });
  assert.equal(api.choosePlace(draft, 'city', { ...city, countryCode: 'US' }), draft);
  draft = api.choosePlace(draft, 'city', city);
  assert.equal(api.locationPatch(draft, []).location.cityLatitude, 41.01);
  draft = api.editLocationDraft(draft, 'district', 'free text');
  assert.equal(api.locationPatch(draft, []), null);
  assert.equal(api.choosePlace(draft, 'district', { ...district, city: 'Ankara' }), draft);
  draft = api.choosePlace(draft, 'district', district);
  const patch = api.locationPatch(draft, [saved]);
  assert.deepEqual(patch.location, saved); assert.equal(patch.city, 'İstanbul / Kadıköy'); assert.deepEqual(patch.recentLocations, [saved]);
  const reopened = api.createLocationDraft(patch);
  assert.deepEqual(reopened.texts, { country: 'Türkiye', city: 'İstanbul', district: 'Kadıköy' });
  assert.deepEqual(api.locationPatch(reopened, []).location, saved);
  draft = api.editLocationDraft(reopened, 'district', '');
  assert.equal(api.locationPatch(draft, []).location.latitude, 41.01);
  draft = api.editLocationDraft(reopened, 'country', 'U');
  assert.equal(draft.city, null); assert.equal(draft.texts.district, ''); assert.equal(api.locationPatch(draft, []), null);
  assert.equal(api.locationPatch(api.choosePlace(api.choosePlace(api.createLocationDraft({}), 'country', { code: 'TR', name: 'Türkiye' }), 'city', { ...city, latitude: null }), []), null);
});
test('recent saves are bounded and newest first, forecast sends exact selected coordinates', () => {
  assert.equal(typeof api.locationPatch, 'function');
  const recents = Array.from({ length: 10 }, (_, i) => ({ ...saved, district: `District ${i}` }));
  const patch = api.locationPatch(api.createLocationDraft({ location: saved }), recents);
  assert.equal(patch.recentLocations.length, 8); assert.deepEqual(patch.recentLocations[0], saved);
  assert.deepEqual(Object.fromEntries(api.weatherParams({ location: saved, city: 'İstanbul / Kadıköy', fahrenheit: true }, 'tr')), { language: 'tr', fahrenheit: '1', latitude: '40.99', longitude: '29.03', place: 'İstanbul / Kadıköy' });
  assert.equal(api.weatherParams({ city: 'İzmir' }, 'tr').get('city'), 'İzmir');
});
test('autocomplete debounces, serializes ignored aborts, suppresses stale results and cancels on dispose', async () => {
  assert.equal(typeof api.createLatestSearch, 'function', 'latest search implementation required');
  const timers = new Map(); let next = 0, now = 0;
  const setTimer = (f, ms) => { timers.set(++next, { f, at: now + ms }); return next; };
  const clearTimer = id => timers.delete(id);
  const advance = ms => { now += ms; for (const [id, t] of [...timers]) if (t.at <= now) { timers.delete(id); t.f(); } };
  const tick = async () => { await new Promise(resolve => setImmediate(resolve)); };
  const requests = [], states = [];
  const search = api.createLatestSearch((query, signal) => new Promise((resolve, reject) => requests.push({ query, signal, resolve, reject })), s => states.push(s), { setTimer, clearTimer });
  search.query('i'); advance(349); assert.equal(requests.length, 0);
  search.query('is'); advance(350); await tick(); assert.equal(requests.length, 1); assert.equal(requests[0].query, 'is');
  search.query('ist'); search.query('istan'); advance(350); await tick(); assert.equal(requests.length, 1); assert.ok(requests[0].signal.aborted);
  requests[0].resolve(['old']); await tick(); assert.equal(requests.length, 2); assert.equal(requests[1].query, 'istan');
  assert.ok(!states.some(s => s.results.includes('old')));
  requests[1].resolve(['latest']); await tick(); assert.deepEqual(states.at(-1).results, ['latest']);
  search.query('district'); advance(350); await tick(); search.cancel(); requests[2].resolve(['canceled']); await tick();
  assert.ok(!states.some(s => s.results.includes('canceled')));
  search.query('offline'); advance(350); await tick(); requests[3].reject(new Error('Offline')); await tick(); assert.match(states.at(-1).error, /Offline/);
  search.retry('offline'); advance(0); await tick(); assert.equal(requests[4].query, 'offline');
  const before = states.length; search.dispose(); requests[4].resolve(['disposed']); await tick(); assert.equal(states.length, before);
  search.query('never'); advance(350); await tick(); assert.equal(requests.length, 5);
});
